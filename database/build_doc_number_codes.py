def _district_code(name: str, taken: set) -> str:
    letters = re.sub(r"[^A-Z]", "", name.upper())
    if len(letters) < 3:
        letters = (letters + "XXX")[:3]
    # 1st choice: first three letters; then first letter + any two later letters
    candidates = [letters[:3]]
    for i in range(1, len(letters)):
        for j in range(i + 1, len(letters)):
            candidates.append(letters[0] + letters[i] + letters[j])
    for c in candidates:
        if c not in taken:
            return c
    n = 1
    while f"{letters[:2]}{n}" in taken:
        n += 1
    return f"{letters[:2]}{n}"


def main():
    # The court lists are kept in the court-scrapers repository. Anywhere else
    # this file is a reference copy: stop instead of writing a wrong file.
    if not (COURTS_CSV.exists() and HC_CSV.exists()):
        raise SystemExit("The court lists are not in this repository. Run this script in court-scrapers, "
                         "then copy 05_doc_number_codes.sql to the other repositories.")
    rows = list(csv.DictReader(open(COURTS_CSV, encoding="utf-8")))
    districts = {}
    for r in rows:
        districts[(r["state_code"], r["district_code"])] = r["district_name"].strip()

    hc_names = {r["court_name"] for r in csv.DictReader(open(HC_CSV, encoding="utf-8"))}
    missing = hc_names - HC.keys()
    if missing:
        raise SystemExit(f"High Courts without a short code: {sorted(missing)}")
    missing_states = {s for s, _ in districts} - DC_STATE.keys()
    if missing_states:
        raise SystemExit(f"District states without a short code: {sorted(missing_states)}")

    out = ["-- Generated by build_doc_number_codes.py -- do not edit by hand.",
           "BEGIN;",
           "DELETE FROM doc_series_codes;"]
    vals = []
    for name, code in sorted(HC.items()):
        vals.append(("hc", name, code, name))
    for s, code in sorted(DC_STATE.items(), key=lambda x: int(x[0])):
        vals.append(("dc_state", s, code, None))

    by_state = {}
    for (s, d), name in sorted(districts.items(), key=lambda x: (int(x[0][0]), int(x[0][1]))):
        taken = by_state.setdefault(s, set())
        code = _district_code(name, taken)
        taken.add(code)
        vals.append(("district", f"{s}_{d}", code, name))

    def q(v):
        return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"
    out.append("INSERT INTO doc_series_codes (kind, key, code, label) VALUES")
    out.append(",\n".join(f"  ({q(k)}, {q(key)}, {q(c)}, {q(l)})" for k, key, c, l in vals) + ";")
    out.append("COMMIT;")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(HC)} High Courts, {len(DC_STATE)} states, {len(districts)} districts")


if __name__ == "__main__":
    main()
